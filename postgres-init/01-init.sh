#!/bin/bash
set -euo pipefail

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    CREATE USER ${DW_ADMIN_USER} WITH PASSWORD '${DW_ADMIN_PASSWORD}';
    CREATE DATABASE ${METABASE_DB_NAME} OWNER ${DW_ADMIN_USER};
    CREATE DATABASE ${DW_DB_NAME} OWNER ${DW_ADMIN_USER};
    CREATE DATABASE ${OLTP_DB_NAME} OWNER ${DW_ADMIN_USER};
EOSQL
